namespace Less3.Publisher.Channels
{
    using System;
    using System.Collections.Generic;
    using System.Linq;
    using System.Text;
    using Less3.Publisher.Manifest;

    /// <summary>
    /// Renders the Inno Setup script for one Windows architecture. The installer shows the logo, the product name,
    /// the tagline and what it installs, and a license page that must be accepted; it adds the install folder to the
    /// system PATH and adds a Start menu entry that runs the server in a per-user folder.
    /// </summary>
    public static class InnoScript
    {
        private const string EnvironmentKey = "SYSTEM\\CurrentControlSet\\Control\\Session Manager\\Environment";

        /// <summary>
        /// Renders the script.
        /// </summary>
        /// <param name="input">Values to render from.</param>
        /// <returns>Inno Setup script text.</returns>
        /// <exception cref="ArgumentNullException">The input is null.</exception>
        /// <exception cref="ArgumentException">The input has no AppId.</exception>
        public static string Render(InnoScriptInput input)
        {
            ArgumentNullException.ThrowIfNull(input);
            if (String.IsNullOrWhiteSpace(input.AppId)) throw new ArgumentException("An Inno Setup AppId GUID is required.", nameof(input));
            ProjectSettings project = input.Project;
            ArtifactSettings artifact = input.Artifact;
            LauncherSettings? launcher = artifact.Launcher;
            string mainExe = artifact.MainExecutable + ".exe";
            StringBuilder s = new StringBuilder();

            s.Append("; Generated by Less3.Publisher from publisher.json. Change the manifest or InnoScript.cs, not this file.\n\n");
            s.Append("[Setup]\n");
            s.Append("AppId={{").Append(input.AppId.Trim('{', '}')).Append("}\n");
            s.Append("AppName=").Append(project.DisplayName).Append('\n');
            s.Append("AppVersion=").Append(input.Version).Append('\n');
            s.Append("AppVerName=").Append(project.DisplayName).Append(' ').Append(input.Version).Append('\n');
            s.Append("AppPublisher=").Append(project.Publisher).Append('\n');
            s.Append("AppPublisherURL=").Append(project.PublisherUrl).Append('\n');
            s.Append("AppSupportURL=").Append(project.Repo).Append("/issues\n");
            s.Append("AppUpdatesURL=").Append(project.Repo).Append("/releases\n");
            s.Append("AppCopyright=Copyright ").Append(project.Publisher).Append('\n');
            s.Append("VersionInfoVersion=").Append(NumericVersion(input.Version)).Append('\n');
            s.Append("VersionInfoCompany=").Append(project.Publisher).Append('\n');
            s.Append("VersionInfoDescription=").Append(project.DisplayName).Append(" Setup\n");
            s.Append("DefaultDirName={autopf}\\").Append(project.DisplayName).Append('\n');
            s.Append("DefaultGroupName=").Append(project.DisplayName).Append('\n');
            s.Append("DisableProgramGroupPage=yes\n");
            s.Append("LicenseFile=").Append(input.LicenseFile).Append('\n');
            s.Append("SetupIconFile=").Append(input.SetupIcon).Append('\n');
            s.Append("UninstallDisplayIcon={app}\\").Append(mainExe).Append('\n');
            s.Append("UninstallDisplayName=").Append(project.DisplayName).Append('\n');
            s.Append("WizardStyle=modern\n");
            if (input.WizardImages.Count > 0) s.Append("WizardImageFile=").Append(String.Join(",", input.WizardImages)).Append('\n');
            if (input.WizardSmallImages.Count > 0) s.Append("WizardSmallImageFile=").Append(String.Join(",", input.WizardSmallImages)).Append('\n');
            s.Append("OutputDir=").Append(input.OutputDir).Append('\n');
            s.Append("OutputBaseFilename=").Append(input.OutputBaseName).Append('\n');
            s.Append("Compression=lzma2/max\n");
            s.Append("SolidCompression=yes\n");
            s.Append("ArchitecturesAllowed=").Append(input.Target.InnoArch).Append('\n');
            s.Append("ArchitecturesInstallIn64BitMode=").Append(input.Target.InnoArch).Append('\n');
            s.Append("PrivilegesRequired=admin\n");
            if (artifact.PathCommands.Count > 0) s.Append("ChangesEnvironment=yes\n");
            s.Append("CloseApplications=yes\n");
            s.Append("RestartApplications=no\n\n");

            s.Append("[Languages]\n");
            s.Append("Name: \"english\"; MessagesFile: \"compiler:Default.isl\"\n\n");

            s.Append("[Messages]\n");
            s.Append("WelcomeLabel2=").Append(MessageText(project.Tagline)).Append("%n%nThis installs:%n");
            foreach (string item in InstallerText.WhatGetsInstalled(project, artifact, OsFamilyEnum.Windows)) s.Append("  - ").Append(MessageText(item)).Append("%n");
            if (!String.IsNullOrEmpty(artifact.InstallerNote)) s.Append("%n").Append(MessageText(artifact.InstallerNote)).Append("%n");
            s.Append("%nStop ").Append(MessageText(project.DisplayName)).Append(" before you continue.\n\n");

            if (launcher != null)
            {
                s.Append("[Tasks]\n");
                s.Append("Name: \"desktopicon\"; Description: \"{cm:CreateDesktopIcon}\"; GroupDescription: \"{cm:AdditionalIcons}\"; Flags: unchecked\n\n");
            }

            s.Append("[Files]\n");
            s.Append("Source: \"").Append(input.PayloadDir.TrimEnd('\\', '/')).Append("\\*\"; DestDir: \"{app}\"; Flags: recursesubdirs createallsubdirs ignoreversion\n");
            s.Append("Source: \"").Append(input.LicenseFile).Append("\"; DestDir: \"{app}\"; Flags: ignoreversion\n");
            if (launcher != null) s.Append("Source: \"").Append(LauncherFile(launcher)).Append("\"; DestDir: \"{app}\"; Flags: ignoreversion\n");
            s.Append('\n');

            if (launcher != null)
            {
                string comment = String.IsNullOrEmpty(launcher.Comment) ? project.Tagline : launcher.Comment;
                s.Append("[Icons]\n");
                s.Append("Name: \"{group}\\").Append(Quote(launcher.DisplayName)).Append("\"; Filename: \"{app}\\").Append(LauncherFile(launcher)).Append("\"; Comment: \"").Append(Quote(comment)).Append("\"; IconFilename: \"{app}\\").Append(mainExe).Append("\"\n");
                s.Append("Name: \"{autodesktop}\\").Append(Quote(launcher.DisplayName)).Append("\"; Filename: \"{app}\\").Append(LauncherFile(launcher)).Append("\"; Comment: \"").Append(Quote(comment)).Append("\"; IconFilename: \"{app}\\").Append(mainExe).Append("\"; Tasks: desktopicon\n\n");

                s.Append("[Run]\n");
                string runNow = String.IsNullOrEmpty(launcher.DataFolder) ? "Run " + project.DisplayName + " now" : "Run " + project.DisplayName + " now (in " + InstallerText.DataFolder(launcher, OsFamilyEnum.Windows) + ")";
                s.Append("Filename: \"{app}\\").Append(LauncherFile(launcher)).Append("\"; Description: \"").Append(Quote(runNow)).Append("\"; Flags: nowait postinstall skipifsilent runasoriginaluser shellexec unchecked\n\n");
            }

            if (artifact.PathCommands.Count > 0)
            {
                s.Append("[Registry]\n");
                s.Append("Root: HKLM; Subkey: \"").Append(EnvironmentKey).Append("\"; ValueType: expandsz; ValueName: \"Path\"; ValueData: \"{olddata};{app}\"; Check: NeedsAddPath(ExpandConstant('{app}'))\n\n");
            }

            s.Append("[Code]\n");
            s.Append("const\n  EnvironmentKey = '").Append(EnvironmentKey).Append("';\n\n");
            s.Append(PathFunctions);
            s.Append("procedure CurUninstallStepChanged(CurUninstallStep: TUninstallStep);\nbegin\n");
            if (artifact.PathCommands.Count > 0) s.Append("  if CurUninstallStep = usPostUninstall then\n    RemovePath(ExpandConstant('{app}'));\n");
            s.Append("end;\n");
            return s.ToString();
        }

        /// <summary>
        /// The launcher's file name in the install folder, for example "start-less3.cmd".
        /// </summary>
        /// <param name="launcher">Launcher settings.</param>
        /// <returns>File name.</returns>
        public static string LauncherFile(LauncherSettings launcher)
        {
            ArgumentNullException.ThrowIfNull(launcher);
            return launcher.FileName + ".cmd";
        }

        /// <summary>
        /// The four-part numeric version Windows file properties need: "0.2.0-alpha" becomes "0.2.0.0".
        /// </summary>
        /// <param name="version">Semantic version.</param>
        /// <returns>Numeric version.</returns>
        public static string NumericVersion(string version)
        {
            string core = (version ?? "0").Split('-', '+')[0];
            List<string> parts = core.Split('.').Select(item => Int32.TryParse(item, out int number) ? number.ToString(System.Globalization.CultureInfo.InvariantCulture) : "0").ToList();
            while (parts.Count < 4) parts.Add("0");
            return String.Join(".", parts.Take(4));
        }

        /// <summary>
        /// Text for an Inno Setup [Messages] entry, where % starts a format sequence: a literal % is written %%.
        /// </summary>
        /// <param name="value">Plain text.</param>
        /// <returns>Escaped text.</returns>
        public static string MessageText(string value)
        {
            return (value ?? "").Replace("%", "%%", StringComparison.Ordinal);
        }

        private static string Quote(string value)
        {
            return (value ?? "").Replace("\"", "\"\"", StringComparison.Ordinal);
        }

        private const string PathFunctions =
            "function NeedsAddPath(Dir: string): Boolean;\n" +
            "var\n  Current: string;\n" +
            "begin\n" +
            "  if not RegQueryStringValue(HKEY_LOCAL_MACHINE, EnvironmentKey, 'Path', Current) then\n" +
            "  begin\n    Result := True;\n    exit;\n  end;\n" +
            "  Result := Pos(';' + Uppercase(Dir) + ';', ';' + Uppercase(Current) + ';') = 0;\n" +
            "end;\n\n" +
            "procedure RemovePath(Dir: string);\n" +
            "var\n  Current: string;\n  Position: Integer;\n" +
            "begin\n" +
            "  if not RegQueryStringValue(HKEY_LOCAL_MACHINE, EnvironmentKey, 'Path', Current) then\n    exit;\n" +
            "  Position := Pos(';' + Uppercase(Dir) + ';', ';' + Uppercase(Current) + ';');\n" +
            "  if Position = 0 then\n    exit;\n" +
            "  if Position = 1 then\n    Delete(Current, 1, Length(Dir) + 1)\n" +
            "  else\n    Delete(Current, Position - 1, Length(Dir) + 1);\n" +
            "  RegWriteExpandStringValue(HKEY_LOCAL_MACHINE, EnvironmentKey, 'Path', Current);\n" +
            "end;\n\n";
    }
}
