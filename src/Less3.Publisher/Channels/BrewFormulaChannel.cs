namespace Less3.Publisher.Channels
{
    using System;
    using System.Collections.Generic;
    using System.Globalization;
    using System.IO;
    using System.Text;

    /// <summary>
    /// Homebrew formula that installs the command from the macOS portable archives. Homebrew downloads with its own
    /// client, so the binary never gets the quarantine attribute and the user never sees Gatekeeper, which makes a
    /// formula the best macOS path for a console app. The workflow commits it to Formula/ in this repository.
    /// </summary>
    public sealed class BrewFormulaChannel : IChannel
    {
        /// <inheritdoc/>
        public string Id => "brew";

        /// <inheritdoc/>
        public string DisplayName => "Homebrew formula";

        /// <inheritdoc/>
        public OsFamilyEnum RequiredHost => OsFamilyEnum.Any;

        /// <inheritdoc/>
        public OsFamilyEnum TargetOs => OsFamilyEnum.MacOs;

        /// <inheritdoc/>
        public IReadOnlyList<ToolRequirement> Tools => Array.Empty<ToolRequirement>();

        /// <inheritdoc/>
        public IReadOnlyList<string> Build(ChannelContext context)
        {
            ArgumentNullException.ThrowIfNull(context);
            string name = context.Option("formulaName", context.Project.Name);
            RuntimeTarget arm = RuntimeTarget.Parse("osx-arm64");
            RuntimeTarget intel = RuntimeTarget.Parse("osx-x64");
            string armFile = AssetNames.Archive(context.Project.Name, context.Version, arm);
            string intelFile = AssetNames.Archive(context.Project.Name, context.Version, intel);
            string armSha = Checksums.Sha256(context.RequireAsset(armFile, "archive"));
            string intelSha = Checksums.Sha256(context.RequireAsset(intelFile, "archive"));

            string output = Path.Combine(ManifestOutput.Directory(context, Id), name + ".rb");
            File.WriteAllText(output, Render(context, name, context.ReleaseAssetUrl(armFile), armSha, context.ReleaseAssetUrl(intelFile), intelSha));
            Console.WriteLine("[brew] wrote " + output + " (commit it to Formula/ in this repository)");
            return new[] { output };
        }

        /// <summary>
        /// Renders the formula.
        /// </summary>
        /// <param name="context">Channel context.</param>
        /// <param name="name">Formula name.</param>
        /// <param name="armUrl">Apple Silicon archive URL.</param>
        /// <param name="armSha">Apple Silicon archive SHA-256.</param>
        /// <param name="intelUrl">Intel archive URL.</param>
        /// <param name="intelSha">Intel archive SHA-256.</param>
        /// <returns>Ruby source.</returns>
        public static string Render(ChannelContext context, string name, string armUrl, string armSha, string intelUrl, string intelSha)
        {
            ArgumentNullException.ThrowIfNull(context);
            StringBuilder s = new StringBuilder();
            s.Append("# Generated by Less3.Publisher from publisher.json for release ").Append(context.Version).Append(".\n");
            s.Append("class ").Append(ClassName(name)).Append(" < Formula\n");
            s.Append("  desc \"").Append(Ruby(context.Project.Tagline.TrimEnd('.'))).Append("\"\n");
            s.Append("  homepage \"").Append(context.Project.Homepage).Append("\"\n");
            s.Append("  version \"").Append(context.Version).Append("\"\n");
            s.Append("  license \"").Append(context.Project.License).Append("\"\n\n");
            s.Append("  on_macos do\n");
            s.Append("    on_arm do\n      url \"").Append(armUrl).Append("\"\n      sha256 \"").Append(armSha).Append("\"\n    end\n");
            s.Append("    on_intel do\n      url \"").Append(intelUrl).Append("\"\n      sha256 \"").Append(intelSha).Append("\"\n    end\n");
            s.Append("  end\n\n");
            s.Append("  def install\n");
            foreach (string command in context.Artifact.PathCommands) s.Append("    bin.install \"").Append(command).Append("\"\n");
            s.Append("  end\n\n");
            s.Append("  test do\n");
            foreach (string command in context.Artifact.PathCommands) s.Append("    assert_predicate bin/\"").Append(command).Append("\", :executable?\n");
            s.Append("  end\n");
            s.Append("end\n");
            return s.ToString();
        }

        /// <summary>
        /// The Ruby class name Homebrew expects for a formula name: "less3" becomes "Less3", "my-tool" "MyTool".
        /// </summary>
        /// <param name="name">Formula name.</param>
        /// <returns>Class name.</returns>
        public static string ClassName(string name)
        {
            StringBuilder s = new StringBuilder();
            foreach (string part in (name ?? "").Split(new[] { '-', '_' }, StringSplitOptions.RemoveEmptyEntries))
            {
                s.Append(Char.ToUpper(part[0], CultureInfo.InvariantCulture)).Append(part.Substring(1));
            }

            return s.ToString();
        }

        private static string Ruby(string value)
        {
            return (value ?? "").Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);
        }
    }
}
