namespace Less3.Publisher.Channels
{
    using System;
    using System.Text;
    using Less3.Publisher.Manifest;

    /// <summary>
    /// Renders the launcher scripts behind the menu entries. Each one creates the per-user data folder, changes into
    /// it, and runs the server there, so the configuration and data it writes to its working directory never land in
    /// the install folder.
    /// </summary>
    public static class LauncherScripts
    {
        /// <summary>
        /// The Windows launcher (.cmd), installed beside the executable. It keeps the console window open after the
        /// server exits so a setup error stays readable.
        /// </summary>
        /// <param name="project">Project settings.</param>
        /// <param name="artifact">Artifact with a launcher.</param>
        /// <returns>Batch file text with CRLF line endings.</returns>
        /// <exception cref="ArgumentException">The artifact has no launcher.</exception>
        public static string WindowsCmd(ProjectSettings project, ArtifactSettings artifact)
        {
            ArgumentNullException.ThrowIfNull(project);
            LauncherSettings launcher = Require(artifact);
            StringBuilder s = new StringBuilder();
            s.Append("@echo off\r\n");
            s.Append("REM Generated by Less3.Publisher. Runs ").Append(project.DisplayName);
            if (!String.IsNullOrEmpty(launcher.DataFolder)) s.Append(" in %USERPROFILE%\\").Append(launcher.DataFolder).Append(", which holds its configuration and data");
            s.Append(".\r\n");
            s.Append("title ").Append(project.DisplayName).Append("\r\n");
            if (!String.IsNullOrEmpty(launcher.DataFolder))
            {
                string folder = "%USERPROFILE%\\" + launcher.DataFolder;
                s.Append("if not exist \"").Append(folder).Append("\" mkdir \"").Append(folder).Append("\"\r\n");
                s.Append("cd /d \"").Append(folder).Append("\"\r\n");
                s.Append("echo Running ").Append(project.DisplayName).Append(" in %CD%\r\n");
            }

            s.Append("\"%~dp0").Append(artifact.MainExecutable).Append(".exe\"");
            if (!String.IsNullOrEmpty(launcher.Arguments)) s.Append(' ').Append(launcher.Arguments);
            s.Append(" %*\r\n");
            s.Append("echo.\r\n");
            s.Append("pause\r\n");
            return s.ToString();
        }

        /// <summary>
        /// The Linux and macOS launcher (POSIX shell). The executable path is resolved before changing directory.
        /// </summary>
        /// <param name="project">Project settings.</param>
        /// <param name="artifact">Artifact with a launcher.</param>
        /// <param name="executable">Shell expression for the executable's absolute path, for example
        /// "/opt/less3/less3" or "$(cd "$(dirname "$0")/../MacOS" &amp;&amp; pwd)/less3".</param>
        /// <param name="pauseAtExit">True to wait for Enter after the server exits, for terminals that close when
        /// their program does.</param>
        /// <returns>Shell script.</returns>
        /// <exception cref="ArgumentException">The artifact has no launcher.</exception>
        public static string Shell(ProjectSettings project, ArtifactSettings artifact, string executable, bool pauseAtExit)
        {
            ArgumentNullException.ThrowIfNull(project);
            LauncherSettings launcher = Require(artifact);
            StringBuilder s = new StringBuilder();
            s.Append("#!/bin/sh\n");
            s.Append("# Generated by Less3.Publisher. Runs ").Append(project.DisplayName);
            if (!String.IsNullOrEmpty(launcher.DataFolder)) s.Append(" in ~/").Append(launcher.DataFolder).Append(", which holds its configuration and data");
            s.Append(".\n");
            s.Append("program=\"").Append(executable).Append("\"\n");
            if (!String.IsNullOrEmpty(launcher.DataFolder))
            {
                s.Append("mkdir -p \"$HOME/").Append(launcher.DataFolder).Append("\" && cd \"$HOME/").Append(launcher.DataFolder).Append("\" || exit 1\n");
                s.Append("echo \"Running ").Append(project.DisplayName).Append(" in $PWD\"\n");
            }

            string arguments = String.IsNullOrEmpty(launcher.Arguments) ? "" : launcher.Arguments + " ";
            if (pauseAtExit)
            {
                s.Append("\"$program\" ").Append(arguments).Append("\"$@\"\n");
                s.Append("status=$?\n");
                s.Append("printf '\\n").Append(project.DisplayName).Append(" exited (%s). Press Enter to close this window.' \"$status\"\n");
                s.Append("read -r _\n");
                s.Append("exit \"$status\"\n");
            }
            else
            {
                s.Append("exec \"$program\" ").Append(arguments).Append("\"$@\"\n");
            }

            return s.ToString();
        }

        /// <summary>
        /// The macOS app bundle's main executable: opens the bundled .command launcher in Terminal. Opening a
        /// .command file needs no automation permission, unlike scripting Terminal.
        /// </summary>
        /// <param name="artifact">Artifact with a launcher.</param>
        /// <returns>Shell script.</returns>
        /// <exception cref="ArgumentException">The artifact has no launcher.</exception>
        public static string MacBundleMain(ArtifactSettings artifact)
        {
            LauncherSettings launcher = Require(artifact);
            return
                "#!/bin/sh\n" +
                "# Generated by Less3.Publisher. Opens the server in a Terminal window.\n" +
                "exec /usr/bin/open -a Terminal \"$(cd \"$(dirname \"$0\")/../Resources\" && pwd)/" + launcher.FileName + ".command\"\n";
        }

        private static LauncherSettings Require(ArtifactSettings artifact)
        {
            ArgumentNullException.ThrowIfNull(artifact);
            return artifact.Launcher ?? throw new ArgumentException("The artifact has no launcher.", nameof(artifact));
        }
    }
}
